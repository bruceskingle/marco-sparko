/// One value and what replaces it.
#[derive(Clone, Debug, PartialEq)]
struct Pair {
    from: String,
    to: String,
}


/// The mapping file: the user's own pairs, which are left as they are, and the generated ones, which are rewritten.
struct Mapping {
    path: PathBuf,
    /// The file up to the generated section, kept as it is, with its comments.
    own_text: String,
    own: Vec<Pair>,
    generated: Vec<Pair>,
}

impl Mapping {
    /// Reads the mapping file, a CSV file with a pair on each line, see csv_line, and lines starting with # which are
    /// comments, the generated pairs after GENERATED_MARKER.
    fn load(path: PathBuf) -> anyhow::Result<Self> {
        let text = fs::read_to_string(&path)
            .map_err(|error| anyhow!("Unable to read the redaction mapping {}: {error}", path.display()))?;
        let (own_text, generated_text) = match text.find(GENERATED_MARKER) {
            Some(index) => (text[..index].to_string(), &text[index..]),
            None => (format!("{}\n\n", text.trim_end()), ""),
        };
        let pairs = |text: &str| -> anyhow::Result<Vec<Pair>> {
            text.lines().enumerate()
                .filter(|(_, line)| !line.trim().is_empty() && !line.starts_with('#'))
                .map(|(index, line)| parse_csv_line(line)
                    .ok_or_else(|| anyhow!("Line {} of the redaction mapping {} is not a pair of values", index + 1, path.display())))
                .collect()
        };
        let own = pairs(&own_text)?;
        let generated = pairs(generated_text)
            .map_err(|_| anyhow!("The generated section of the redaction mapping {} has a line which is not a pair of values", path.display()))?;
        Ok(Mapping { path, own_text, own, generated })
    }

    fn save(&self) -> anyhow::Result<()> {
        let mut text = self.own_text.clone();
        text.push_str(GENERATED_MARKER);
        text.push_str(", for identifiers it found which are not above.\n");
        let width = csv_width(&self.generated);
        for pair in &self.generated {
            text.push_str(&csv_line(pair, width));
            text.push('\n');
        }
        let mut file = private_file::create_private_file(&self.path)?;
        std::io::Write::write_all(&mut file, text.as_bytes())?;
        Ok(())
    }

    /// Every pair, the user's first so that they win.
    fn pairs(&self) -> impl Iterator<Item = &Pair> {
        self.own.iter().chain(self.generated.iter())
    }

    fn contains(&self, value: &str) -> bool {
        self.pairs().any(|pair| pair.from.eq_ignore_ascii_case(value))
    }

    /// Makes up a replacement for each value found which is not in the mapping, nor a made up one, and adds them to
    /// the generated pairs. Returns how many of each kind were added.
    fn add(&mut self, found: &Found) -> BTreeMap<Kind, usize> {
        let made_up: HashSet<String> = self.pairs().map(|pair| pair.to.to_lowercase()).collect();
        let mut rng = rand::rng();
        let mut added = BTreeMap::<Kind, usize>::new();
        for (value, (kind, _)) in &found.values {
            if self.contains(value) || made_up.contains(&value.to_lowercase()) {
                continue;
            }
            let number = self.generated.len() + 1;
            let mut to = make_up(value, *kind, number, &mut rng);
            // Made up IDs must not be the same as another value, made up or not.
            while self.pairs().any(|pair| pair.to == to) || found.values.contains_key(&to) {
                to = make_up(value, *kind, number, &mut rng);
            }
            self.generated.push(Pair { from: value.clone(), to });
            *added.entry(*kind).or_default() += 1;
        }
        added
    }
}

/// A value as a field of the mapping file: in double quotes, with each double quote in it doubled, if it has a comma or
/// double quote in it, or starts with # or a space, or ends with a space, as unquoted values are trimmed.
fn csv_field(value: &str) -> String {
    if value.contains([',', '"']) || value.starts_with(['#', ' ']) || value.ends_with(' ') {
        format!("\"{}\"", value.replace('"', "\"\""))
    }
    else {
        value.to_string()
    }
}

/// A pair as a line of the mapping file: the real value, a comma, spaces to make the real value and the comma width
/// characters wide, so that the made up values line up, then the made up value.
fn csv_line(pair: &Pair, width: usize) -> String {
    let from = format!("{},", csv_field(&pair.from));
    format!("{from:<width$} {}", csv_field(&pair.to))
}

/// The width of the real values and their commas, for csv_line, the longest up to MAX_ALIGNED, so that one long value
/// does not push the made up values far to the right.
fn csv_width(pairs: &[Pair]) -> usize {
    const MAX_ALIGNED: usize = 40;
    pairs.iter().map(|pair| csv_field(&pair.from).chars().count() + 1).filter(|width| *width <= MAX_ALIGNED).max().unwrap_or(0)
}

/// The pair on a line of the mapping file, see csv_line, or None if it is not two values. Spaces around a value are
/// ignored unless it is in double quotes.
fn parse_csv_line(line: &str) -> Option<Pair> {
    let mut fields = Vec::new();
    let mut chars = line.chars().peekable();
    loop {
        let mut field = String::new();
        while chars.peek() == Some(&' ') {
            chars.next();
        }
        let quoted = chars.peek() == Some(&'"');
        if quoted {
            chars.next();
            loop {
                match chars.next()? {
                    '"' if chars.peek() == Some(&'"') => {
                        chars.next();
                        field.push('"');
                    },
                    '"' => break,
                    c => field.push(c),
                }
            }
        }
        let mut rest = String::new();
        while let Some(&c) = chars.peek() {
            if c == ',' {
                break;
            }
            rest.push(c);
            chars.next();
        }
        // After a quoted value only spaces, before the next comma.
        if quoted {
            if !rest.trim().is_empty() {
                return None;
            }
        }
        else {
            field.push_str(rest.trim_end());
        }
        fields.push(field);
        if chars.next().is_none() {
            break;
        }
    }
    match <[String; 2]>::try_from(fields) {
        Ok([from, to]) if !from.is_empty() => Some(Pair { from, to }),
        _ => None,
    }
}

/// The kinds of identifying value, which are made up differently.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum Kind {
    /// An ID or reference, made up with the same shape, e.g. digits for digits.
    Id,
    Name,
    Address,
    Email,
    Phone,
    Postcode,
    Coordinate,
    DateOfBirth,
}

/// The kind of identifying value in a field, by its name. fullName and displayName are a person's in an object with
/// their other names, otherwise e.g. a tariff's.
fn field_kind(field: &str, object: &serde_json::Map<String, Value>) -> Option<Kind> {
    let person = object.contains_key("givenName") || object.contains_key("familyName") || object.contains_key("email");
    match field {
        "id" | "number" | "accountNumber" | "mpan" | "mprn" | "serialNumber" | "deviceId" | "nodeId" | "propertyId"
        | "userId" | "billingDocumentIdentifier" => Some(Kind::Id),
        "givenName" | "familyName" | "preferredName" | "billingName" | "billingSubName" => Some(Kind::Name),
        "fullName" | "displayName" if person => Some(Kind::Name),
        "address" | "toAddress" => Some(Kind::Address),
        "email" | "billingEmail" => Some(Kind::Email),
        "landline" | "mobile" | "alternativePhoneNumbers" => Some(Kind::Phone),
        "postcode" => Some(Kind::Postcode),
        "latitude" | "longitude" => Some(Kind::Coordinate),
        "dateOfBirth" => Some(Kind::DateOfBirth),
        _ => None,
    }
}

/// The shapes of identifying values wherever they are, e.g. in records stored as lists of values, and in file names.
struct Patterns {
    account: Regex,
    device: Regex,
    uuid: Regex,
    quoted_digits: Regex,
    email: Regex,
    secrets: Vec<Regex>,
}

impl Patterns {
    fn new() -> Self {
        Patterns {
            account: Regex::new(r"\bA-[0-9A-F]{8}\b").unwrap(),
            device: Regex::new(r"\b[0-9A-Fa-f]{2}(?:-[0-9A-Fa-f]{2}){7}\b").unwrap(),
            uuid: Regex::new(r"\b[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\b").unwrap(),
            quoted_digits: Regex::new(r#""([0-9]{6,})""#).unwrap(),
            email: Regex::new(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+").unwrap(),
            secrets: vec![
                // Octopus API keys, and JSON web tokens.
                Regex::new(r"sk_live_[A-Za-z0-9]+").unwrap(),
                Regex::new(r"eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+").unwrap(),
            ],
        }
    }

    fn remove_secrets(&self, text: &str) -> String {
        let mut text = text.to_string();
        for secret in &self.secrets {
            text = secret.replace_all(&text, SECRET).into_owned();
        }
        text
    }

    fn has_secret(&self, text: &str) -> bool {
        self.secrets.iter().any(|secret| secret.is_match(text))
    }
}

/// The identifying values in a file, with their kinds, and where they were found, e.g. the field, for reporting.
#[derive(Default)]
struct Found {
    values: BTreeMap<String, (Kind, String)>,
}

impl Found {
    fn add(&mut self, value: &str, kind: Kind, place: &str) {
        let value = value.trim();
        // A short ID, e.g. "1", or part of an address, e.g. a country code, is not identifying, and replacing it
        // everywhere would change other values.
        if value.is_empty()
            || (kind == Kind::Id && (value.len() < 5 || !value.chars().any(|c| c.is_ascii_digit())))
            || (kind == Kind::Address && value.len() < 4)
        {
            return;
        }
        self.values.entry(value.to_string()).or_insert((kind, place.to_string()));
    }

    /// The identifying values in a file's name and contents.
    fn scan(&mut self, patterns: &Patterns, name: &str, text: &str) {
        for part in name.split(['#', '/', '\\']) {
            if part.len() >= 6 && part.chars().all(|c| c.is_ascii_digit()) {
                self.add(part, Kind::Id, "file name");
            }
        }
        for source in [name, text] {
            for found in patterns.account.find_iter(source).chain(patterns.device.find_iter(source)).chain(patterns.uuid.find_iter(source)) {
                self.add(found.as_str(), Kind::Id, "an ID");
            }
            for found in patterns.email.find_iter(source) {
                self.add(found.as_str(), Kind::Email, "an email address");
            }
        }
        for found in patterns.quoted_digits.captures_iter(text) {
            self.add(&found[1], Kind::Id, "a number");
        }
        // Whole files of JSON, or a JSON record on each line.
        match serde_json::from_str::<Value>(text) {
            Ok(value) => self.scan_json(&value),
            Err(_) => {
                for line in text.lines() {
                    if let Ok(value) = serde_json::from_str::<Value>(line) {
                        self.scan_json(&value);
                    }
                }
            },
        }
    }

    fn scan_json(&mut self, value: &Value) {
        match value {
            Value::Object(object) => {
                for (field, value) in object {
                    match field_kind(field, object) {
                        Some(kind) => self.add_values(value, kind, field),
                        None => self.scan_json(value),
                    }
                }
            },
            Value::Array(values) => values.iter().for_each(|value| self.scan_json(value)),
            _ => {},
        }
    }

    fn add_values(&mut self, value: &Value, kind: Kind, field: &str) {
        match value {
            // Each line of an address, as in the files its lines are separated by an escape, \n, not a new line.
            Value::String(text) if text.contains('\n') => {
                for line in text.lines().map(str::trim) {
                    self.add(line, kind, field);
                }
            },
            Value::String(text) => self.add(text, kind, field),
            Value::Number(number) => self.add(&number.to_string(), kind, field),
            Value::Array(values) => values.iter().for_each(|value| self.add_values(value, kind, field)),
            // The parts of e.g. an address, apart from its country, which does not identify anyone.
            Value::Object(object) => object.iter()
                .filter(|(key, _)| !key.to_lowercase().contains("country"))
                .for_each(|(_, value)| self.add_values(value, kind, field)),
            _ => {},
        }
    }
}

/// A made up replacement for value, of the same shape: digits for digits, letters for letters, the rest kept, so that
/// it is still recognised as what it is, e.g. an account number keeps its A- prefix.
fn same_shape(value: &str, rng: &mut impl Rng) -> String {
    let (prefix, rest) = value.strip_prefix("A-").map_or(("", value), |rest| ("A-", rest));
    let hex = rest.chars().filter(|c| c.is_ascii_alphabetic()).all(|c| c.is_ascii_hexdigit());
    let mut made_up = String::from(prefix);
    for (index, c) in rest.chars().enumerate() {
        made_up.push(match c {
            '0'..='9' if index == 0 && c != '0' => char::from(b'1' + rng.random_range(0..9u8)),
            '0'..='9' => char::from(b'0' + rng.random_range(0..10u8)),
            'A'..='Z' if hex => char::from(b'A' + rng.random_range(0..6u8)),
            'a'..='z' if hex => char::from(b'a' + rng.random_range(0..6u8)),
            'A'..='Z' => char::from(b'A' + rng.random_range(0..26u8)),
            'a'..='z' => char::from(b'a' + rng.random_range(0..26u8)),
            c => c,
        });
    }
    made_up
}

/// A made up replacement for a value of kind, the number'th of its kind.
fn make_up(value: &str, kind: Kind, number: usize, rng: &mut impl Rng) -> String {
    match kind {
        Kind::Name => format!("Name{number}"),
        Kind::Address => format!("Address {number}"),
        Kind::Email => format!("person{number}@example.com"),
        Kind::DateOfBirth => String::from("1980-01-01"),
        Kind::Id | Kind::Phone | Kind::Postcode | Kind::Coordinate => same_shape(value, rng),
    }
}

/// Replaces whole values, longest first, ignoring case, keeping the case of what it replaces where it is all upper or
/// lower case.
struct Replacer {
    matcher: AhoCorasick,
    pairs: Vec<Pair>,
}

impl Replacer {
    fn new(pairs: Vec<Pair>) -> anyhow::Result<Self> {
        let matcher = AhoCorasickBuilder::new()
            .ascii_case_insensitive(true)
            .match_kind(MatchKind::LeftmostLongest)
            .build(pairs.iter().map(|pair| &pair.from))?;
        Ok(Replacer { matcher, pairs })
    }

    /// Whether the match from start to end is a whole value, not part of a longer word or number.
    /// A value straight after an escape such as the \n between the lines of an address in JSON is whole too.
    fn is_whole(text: &str, start: usize, end: usize, value: &str) -> bool {
        let digits = value.chars().all(|c| c.is_ascii_digit() || c == '.');
        let joins = |c: char| c.is_alphanumeric() || c == '_' || (digits && (c == '.' || c.is_ascii_digit()));
        let mut before = text[..start].chars().rev();
        let escaped = matches!((before.next(), before.next()), (Some('n' | 'r' | 't'), Some('\\')));
        (escaped || !text[..start].chars().next_back().is_some_and(joins)) && !text[end..].chars().next().is_some_and(joins)
    }

    fn replace(&self, text: &str) -> String {
        let mut result = String::with_capacity(text.len());
        let mut last = 0;
        for found in self.matcher.find_iter(text) {
            let pair = &self.pairs[found.pattern().as_usize()];
            if !Self::is_whole(text, found.start(), found.end(), &pair.from) {
                continue;
            }
            let matched = &text[found.start()..found.end()];
            result.push_str(&text[last..found.start()]);
            let has_letters = matched.chars().any(char::is_alphabetic);
            if matched != pair.from && has_letters && matched == matched.to_uppercase() {
                result.push_str(&pair.to.to_uppercase());
            }
            else if matched != pair.from && has_letters && matched == matched.to_lowercase() {
                result.push_str(&pair.to.to_lowercase());
            }
            else {
                result.push_str(&pair.to);
            }
            last = found.end();
        }
        result.push_str(&text[last..]);
        result
    }

    /// Whether any of the values is in text as a whole value, apart from those kept as they are, i.e. replaced by
    /// themselves, e.g. placeholders.
    fn finds(&self, text: &str) -> bool {
        self.matcher.find_iter(text).any(|found| {
            let pair = &self.pairs[found.pattern().as_usize()];
            !pair.from.eq_ignore_ascii_case(&pair.to) && Self::is_whole(text, found.start(), found.end(), &pair.from)
        })
    }
}

/// The files under dir, as their paths relative to it, and their contents.
fn read_tree(dir: &Path) -> anyhow::Result<Vec<(String, String)>> {
    let mut files = Vec::new();
    let mut dirs = vec![dir.to_path_buf()];
    while let Some(current) = dirs.pop() {
        for entry in fs::read_dir(&current)? {
            let entry = entry?;
            let path = entry.path();
            if entry.file_type()?.is_dir() {
                dirs.push(path);
                continue;
            }
            let relative = path.strip_prefix(dir)?.to_string_lossy().replace('\\', "/");
            let text = fs::read_to_string(&path)
                .map_err(|error| anyhow!("Unable to read {relative}, which is not text: {error}"))?;
            files.push((relative, text));
        }
    }
    files.sort();
    Ok(files)
}

/// When the newest of the profile from's data files was written, i.e. when its data was last fetched, as a unix
/// timestamp.
fn newest_file_time(cache_dir: &Path, from: &str, module_ids: &[&String]) -> Option<i64> {
    let mut newest = None;
    let mut dirs: Vec<PathBuf> = module_ids.iter().map(|module_id| cache_dir.join(format!("{from}-{module_id}"))).collect();
    while let Some(dir) = dirs.pop() {
        for entry in fs::read_dir(&dir).ok()?.flatten() {
            let path = entry.path();
            if path.is_dir() {
                dirs.push(path);
            }
            else if let Ok(modified) = entry.metadata().and_then(|metadata| metadata.modified())
                && let Ok(time) = modified.duration_since(std::time::UNIX_EPOCH)
            {
                newest = newest.max(Some(time.as_secs() as i64));
            }
        }
    }
    newest
}

/// The mapping file, in the real home directory, not the data directory, so that it is not with the data.
fn mapping_path() -> anyhow::Result<PathBuf> {
    Ok(std::env::home_dir().ok_or_else(|| anyhow!("Unable to find the home directory"))?.join(MAPPING_FILE))
}

/// Copies the cached data of the profile from to a new, offline, profile to, redacted, see the module documentation.
/// Prints what it does, for --redact.
pub fn redact_profile(from: &str, to: &str) -> anyhow::Result<()> {
    if !crate::profile::is_valid_profile_name(to) {
        bail!("The new profile's name must contain only letters, digits and underscores");
    }
    if profile_names_equal(from, to) {
        bail!("The new profile must have a different name to the one it is redacted from");
    }
    let profiles: ProfileFile = serde_json::from_reader(fs::File::open(MarcoSparkoContext::get_file_path()?)?)?;
    let source = profiles.iter().find(|profile| profile_names_equal(&profile.name, from))
        .ok_or_else(|| anyhow!("There is no profile {from}"))?;
    if let Some(existing) = profiles.iter().find(|profile| profile_names_equal(&profile.name, to))
        && !existing.offline
    {
        bail!("There is already a profile {to} which is not a redacted one, so it is not replaced");
    }

    let mut mapping = Mapping::load(mapping_path()?)?;
    let patterns = Patterns::new();
    let cache_dir = MarcoSparkoContext::get_cache_dir_path()?;
    let module_ids: Vec<&String> = source.modules.keys().collect();

    // Find the identifiers which are not in the mapping yet, and make up replacements for them.
    let mut sources = Vec::new();
    let mut found = Found::default();
    for module_id in &module_ids {
        let dir = cache_dir.join(format!("{from}-{module_id}"));
        if !dir.is_dir() {
            continue;
        }
        let files = read_tree(&dir)?;
        for (name, text) in &files {
            found.scan(&patterns, name, text);
        }
        sources.push((module_id.to_string(), files));
    }
    let added = mapping.add(&found);
    // Saved before the copy is made, so that the replacements are the same next time even if the copy fails.
    mapping.save()?;

    // Copy the files, replacing everything in the mapping, and check the copy.
    let replacer = Replacer::new(mapping.pairs().cloned().collect())?;
    let made_up: HashSet<String> = mapping.pairs().map(|pair| pair.to.to_lowercase()).collect();
    let mut problems = Vec::new();
    let mut copies = Vec::new();
    let mut file_count = 0;
    for (module_id, files) in &sources {
        let target_dir = cache_dir.join(format!("{to}-{module_id}"));
        for (name, text) in files {
            let new_name = replacer.replace(name);
            let new_text = replacer.replace(&patterns.remove_secrets(text));
            problems.extend(check(&replacer, &patterns, &made_up, &format!("{module_id}/{new_name}"), &new_name, &new_text));
            copies.push((target_dir.join(&new_name), new_text));
            file_count += 1;
        }
    }
    if !problems.is_empty() {
        problems.sort();
        problems.dedup();
        bail!("The redacted copy was not made, as it would still identify you:\n  {}", problems.join("\n  "));
    }

    // Replace any previous redacted copy.
    for module_id in &module_ids {
        let target_dir = cache_dir.join(format!("{to}-{module_id}"));
        if target_dir.exists() {
            fs::remove_dir_all(&target_dir)?;
        }
    }
    for (path, text) in &copies {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        let mut file = private_file::create_private_file(path)?;
        std::io::Write::write_all(&mut file, text.as_bytes())?;
    }
    crate::profile::save_redacted_profile(source, to, newest_file_time(&cache_dir, from, &module_ids))?;

    println!("Redacted {file_count} files of profile {from} into profile {to}, which is offline.");
    report_added(&added, &mapping);
    Ok(())
}

fn report_added(added: &BTreeMap<Kind, usize>, mapping: &Mapping) {
    if added.is_empty() {
        println!("Every identifier was already in {}.", mapping.path.display());
    }
    else {
        let added: Vec<String> = added.iter().map(|(kind, count)| format!("{count} {kind:?}")).collect();
        println!("Added replacements for {} new identifiers to {}.", added.join(", "), mapping.path.display());
    }
}

/// What is wrong with a redacted file, called label in the report, whose name and text are given: an original value
/// or secret left in it, or an identifier which is not a made up one.
fn check(replacer: &Replacer, patterns: &Patterns, made_up: &HashSet<String>, label: &str, name: &str, text: &str) -> Vec<String> {
    let mut problems = Vec::new();
    if replacer.finds(name) || replacer.finds(text) {
        problems.push(format!("{label} still has an original value"));
    }
    if patterns.has_secret(text) {
        problems.push(format!("{label} still has a secret"));
    }
    let mut left = Found::default();
    left.scan(patterns, name, text);
    for (value, (kind, place)) in &left.values {
        if !made_up.contains(&value.to_lowercase()) && value != SECRET {
            problems.push(format!("{label} has a {kind:?} in {place} which was not replaced"));
        }
    }
    problems
}

/// Redacts a document, replacing everything in the mapping, then secrets as the documents always have. The whole
/// document is redacted, not only its code blocks, as identifiers have been found in the text too.
fn redact_document(text: &str, replacer: &Replacer) -> String {
    let api_key = Regex::new("sk_live_[a-zA-Z0-9]*").unwrap();
    let refresh_token = Regex::new("\"[a-zA-Z0-9]{60,70}\"").unwrap();
    let token = Regex::new("\"[^\"]{800,900}\"").unwrap();
    // Line by line, so that a pattern never matches across lines.
    replacer.replace(text).split_inclusive('\n')
        .map(|line| {
            let line = api_key.replace_all(line, DOCS_API_KEY);
            let line = refresh_token.replace_all(&line, DOCS_REFRESH_TOKEN);
            token.replace_all(&line, DOCS_TOKEN).into_owned()
        })
        .collect()
}

/// Redacts the documents in unredacted_docs, which is not in the repository, into docs, replacing those there, for
/// --redact docs, see redact_document. Run from the repository's directory. Prints what it does.
pub fn redact_docs() -> anyhow::Result<()> {
    let source = PathBuf::from("unredacted_docs");
    let target = PathBuf::from("docs");
    if !source.is_dir() || !target.is_dir() {
        bail!("There is no unredacted_docs or docs directory here, run this in the repository's directory");
    }
    let files = read_tree(&source)?;
    let mut mapping = Mapping::load(mapping_path()?)?;
    let patterns = Patterns::new();
    let mut found = Found::default();
    for (_, text) in files.iter().filter(|(name, _)| name.ends_with(".md")) {
        found.scan(&patterns, "", text);
    }
    let added = mapping.add(&found);
    mapping.save()?;

    let replacer = Replacer::new(mapping.pairs().cloned().collect())?;
    let made_up: HashSet<String> = mapping.pairs().map(|pair| pair.to.to_lowercase()).collect();
    let mut problems = Vec::new();
    let mut copies = Vec::new();
    for (name, text) in &files {
        let new_text = if name.ends_with(".md") { redact_document(text, &replacer) } else { text.clone() };
        problems.extend(check(&replacer, &patterns, &made_up, name, "", &new_text));
        copies.push((target.join(name), new_text));
    }
    if !problems.is_empty() {
        problems.sort();
        problems.dedup();
        bail!("The documents were not redacted, as they would still identify you:\n  {}", problems.join("\n  "));
    }
    for (path, text) in &copies {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(path, text)?;
    }
    println!("Redacted {} documents from {} into {}.", copies.len(), source.display(), target.display());
    report_added(&added, &mapping);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{Pair, Replacer, csv_line, parse_csv_line, same_shape};

    #[test]
    fn whole_values_are_replaced_in_any_case() {
        let replacer = Replacer::new(vec![
            Pair { from: String::from("Cambridgeshire"), to: String::from("Borsetshire") },
            Pair { from: String::from("Cambridge"), to: String::from("Borchester") },
            Pair { from: String::from("1234567"), to: String::from("7654321") },
        ]).unwrap();
        assert_eq!(replacer.replace("Cambridge, Cambridgeshire, CAMBRIDGE, cambridge"), "Borchester, Borsetshire, BORCHESTER, borchester");
        assert_eq!(replacer.replace("[\"1234567\",1234567,0.1234567,12345678,A1234567]"), "[\"7654321\",7654321,0.1234567,12345678,A1234567]");
        // Lines of an address in JSON.
        assert_eq!(replacer.replace("\"1 Road\\nCambridge\\nCAMBRIDGESHIRE\""), "\"1 Road\\nBorchester\\nBORSETSHIRE\"");
        assert!(replacer.finds("x\\nCambridge"));
        assert!(replacer.finds("x 1234567 y"));
        assert!(!replacer.finds("x 91234567 y"));
    }

    #[test]
    fn pairs_are_read_back_as_they_were_written() {
        for pair in [
            Pair { from: String::from("Real"), to: String::from("Made Up") },
            Pair { from: String::from("1, The Street"), to: String::from("Address 1") },
            Pair { from: String::from("Say \"hello\""), to: String::from("#1") },
        ] {
            assert_eq!(parse_csv_line(&csv_line(&pair, 20)), Some(pair));
        }
        let street = Pair { from: String::from("1, The Street"), to: String::from("Address 1") };
        assert_eq!(csv_line(&street, 20), "\"1, The Street\",     Address 1");
        assert_eq!(parse_csv_line("\"1, The Street\" ,   Address 1  "), Some(street));
        assert_eq!(parse_csv_line("\" padded \",x"), Some(Pair { from: String::from(" padded "), to: String::from("x") }));
        assert_eq!(parse_csv_line("one value"), None);
        assert_eq!(parse_csv_line("a,b,c"), None);
    }

    #[test]
    fn made_up_ids_keep_their_shape() {
        let mut rng = rand::rng();
        let account = same_shape("A-B1C2D34E", &mut rng);
        assert!(account.starts_with("A-") && account.len() == 10, "{account}");
        assert!(account[2..].chars().all(|c| c.is_ascii_hexdigit() && !c.is_ascii_lowercase()), "{account}");
        let device = same_shape("01-23-45-67-89-AB-CD-EF", &mut rng);
        assert_eq!(device.matches('-').count(), 7, "{device}");
        let number = same_shape("1012345678901", &mut rng);
        assert!(number.len() == 13 && number.chars().all(|c| c.is_ascii_digit()) && !number.starts_with('0'), "{number}");
    }
}
